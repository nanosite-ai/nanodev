#!/usr/bin/env node
// Copies nano-site modules nanodev needs at runtime into src/vendor/, so the published CLI does not depend on
// unpublished workspaces (@nanosite/contracts). The source in the monorepo stays the single source of truth:
// edit it there, run `npm run vendor -w @nanosite/nanodev`, commit both. src/vendor/vendor.test.mts fails
// when a copy drifts from its source.
//
//   node scripts/vendor.mjs          write the copies
//   node scripts/vendor.mjs --check  exit 1 when a copy is stale
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = path.resolve(PACKAGE_ROOT, "..", "..");

/** Vendored file (relative to the package) → its source (relative to the nano-site repo root). */
export const VENDORED = {
  "src/vendor/lockfile.mts": "packages/contracts/src/lockfile.mts",
};

export const vendorHeader = (source) =>
  `// GENERATED by scripts/vendor.mjs from nano-site's ${source}. Do not edit here: edit the source and run\n` +
  `// \`npm run vendor -w @nanosite/nanodev\`. Vendored so the published CLI needs no unpublished workspace.\n`;

/** The vendored file's expected content, or null when the source isn't there (outside the monorepo). */
export const expectedVendored = (source, repoRoot = REPO_ROOT) => {
  const abs = path.join(repoRoot, source);
  if (!existsSync(abs)) return null;
  return vendorHeader(source) + readFileSync(abs, "utf8").replace(/\r\n/g, "\n");
};

const main = () => {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [target, source] of Object.entries(VENDORED)) {
    const expected = expectedVendored(source);
    if (expected === null) {
      process.stdout.write(`skip ${target}: ${source} not found (not in the nano-site monorepo)\n`);
      continue;
    }
    const abs = path.join(PACKAGE_ROOT, target);
    const current = existsSync(abs) ? readFileSync(abs, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === expected) continue;
    if (check) {
      process.stderr.write(`stale: ${target} (from ${source}): run npm run vendor -w @nanosite/nanodev\n`);
      stale++;
    } else {
      writeFileSync(abs, expected);
      process.stdout.write(`updated ${target}\n`);
    }
  }
  if (stale > 0) process.exitCode = 1;
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
